import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
import {realpathSync,mkdirSync,writeFileSync,readFileSync} from 'node:fs';
import {pathToFileURL} from 'node:url';
import {unzipSync,strFromU8} from 'fflate';
const require=createRequire(realpathSync('node_modules/wrangler')+'/package.json'),{build}=require('esbuild');
mkdirSync('.sites-runtime',{recursive:true});
await build({entryPoints:['lib/cart-export.ts'],outfile:'.sites-runtime/cart-export-test.mjs',bundle:true,platform:'node',format:'esm'});
const {cartExportRows,cartSpreadsheetBytes}=await import(pathToFileURL(realpathSync('.sites-runtime/cart-export-test.mjs')));
const item={id:'a',name:'אתר & בדיקה',url:'https://example.test/a?x=1&y=2',dr:0,ur:42,regular_price:20000,publication_price:15000,quantity:2,editorial_price:6000,price_cents:21000};
const q={items:[item],subtotal:42000,discount:4200,vat:6804,total:44604};
const rows=cartExportRows(q);
assert.deepEqual(rows[1],[item.name,item.url,0,42,200,150,2,300,120,420]);
assert.deepEqual(rows.slice(-5).map(r=>r[1]),[420,42,378,68.04,446.04]);
assert.equal(cartExportRows({...q,items:[{...item,publication_price:0,editorial_price:0,price_cents:0,dr:null,ur:null}]})[1][5],0,'zero personal price stays zero');
assert.equal(cartExportRows({...q,items:[{...item,dr:null,ur:null}]})[1][2],'','unknown DR stays blank');
assert.equal(cartExportRows({...q,items:[{...item,publication_price:22000,price_cents:28000}]})[1][5],220,'personal price is not clamped to list price');
assert.throws(()=>cartExportRows({...q,items:[{...item,publication_price:undefined}]}));
assert.throws(()=>cartExportRows({...q,items:[]}));
const files=unzipSync(cartSpreadsheetBytes(q));
const sheet=strFromU8(files['xl/worksheets/sheet1.xml']),styles=strFromU8(files['xl/styles.xml']);
assert(sheet.includes('rightToLeft="1"'));assert(sheet.includes('<pane'));assert(sheet.includes('<autoFilter ref="A1:J2"'));assert(sheet.includes('width="48"'));
assert(sheet.includes('<c r="F2" s="2"><v>150</v></c>'),'price is a numeric Excel cell');
assert(sheet.includes('אתר &amp; בדיקה'));assert(styles.includes('#,##0.00&quot; ₪&quot;'));
assert(strFromU8(files['xl/_rels/workbook.xml.rels']).includes('Target="styles.xml"'));
assert(strFromU8(files['[Content_Types].xml']).includes('/xl/styles.xml'));
const formulaRow=cartExportRows({...q,items:[{...item,name:'=HYPERLINK("bad")'}]});
const injection=strFromU8(unzipSync(cartSpreadsheetBytes({...q,items:[{...item,name:formulaRow[1][0]}]}))['xl/worksheets/sheet1.xml']);
assert(!injection.includes('<f>'),'user text never becomes a spreadsheet formula');
const route=readFileSync('app/api/[...path]/route.ts','utf8');assert(route.includes('dr: site.dr ?? null, ur: site.ur ?? null'));
writeFileSync('.sites-runtime/cart-export-verification.xlsx',cartSpreadsheetBytes(q));
console.log('CART EXPORT PASS: authenticated quote prices, zero/personal pricing, quantity/writing/coupon/VAT reconciliation, missing metrics, numeric currency cells, RTL/filter/frozen header, escaped literal text.');
