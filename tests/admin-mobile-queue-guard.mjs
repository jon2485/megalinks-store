import assert from 'node:assert/strict';
import {compile,reset,render,nodes,text} from './admin-ui-harness.mjs';

const {default:Lobby}=await compile('app/admin-lobby.tsx','admin-mobile-queue-guard',{
 stubs:{'./admin-lobby-panels':'export default function Panel(){return null}'},
});
const h=reset({'admin/control-center':{data:{queues:[{id:'payment_reports',count:3}],email_ready:true}}});
const modals=[];let focused=0,closed=0;
const ctx={revision:0,adminMode:true,user:{role:'admin'},go(){throw Error('Queue selection must stay local')},refresh(){},open(m){modals.push(m);}};
const view=()=>render(Lobby,{ctx});
const toggle=t=>nodes(t).find(n=>n.props['aria-controls']==='admin-v172-queues');
const queue=(t,id)=>nodes(t).find(n=>n.type==='button'&&n.props.id==='lobby-tab-'+id);
const selected=t=>nodes(t).find(n=>n.type==='button'&&n.props['aria-pressed']&&n.props.id?.startsWith('lobby-tab-')).props.id;
const panel=t=>nodes(t).find(n=>n.props.ctx&&n.props.page).props.page;
let tree=view();
h.refs[2].current={getClientRects:()=>[{}],focus(){focused++;}};
toggle(tree).props.onClick();tree=view();
h.refs[0].current=true;
queue(tree,'cancellations').props.onClick();tree=view();
assert.equal(modals.length,1,'Exactly one original dirty confirmation opens');
assert.equal(toggle(tree).props['aria-expanded'],true,'Disclosure stays open while decision is pending');
assert.equal(selected(tree),'lobby-tab-payment_reports');
assert.equal(panel(tree),'lobby-payment-reports');
assert.equal(focused,0,'Do not move focus to the queue toggle before approval');
let dialog=modals[0].render(()=>{closed++;});
nodes(dialog).find(n=>n.type==='button'&&text(n)==='המשך עריכה').props.onClick();tree=view();
assert.equal(closed,1);
assert.equal(toggle(tree).props['aria-expanded'],true,'Continue editing preserves the open selector');
assert.equal(selected(tree),'lobby-tab-payment_reports');
assert.equal(panel(tree),'lobby-payment-reports');
assert.equal(h.refs[0].current,true,'Continue editing does not clear dirty state');
assert.equal(focused,0);
queue(tree,'cancellations').props.onClick();tree=view();
assert.equal(modals.length,2);
assert.equal(toggle(tree).props['aria-expanded'],true);
dialog=modals[1].render(()=>{closed++;});
nodes(dialog).find(n=>n.type==='button'&&text(n)==='יציאה ללא שמירה').props.onClick();tree=view();
assert.equal(closed,2);
assert.equal(toggle(tree).props['aria-expanded'],false,'Close only after approved navigation');
assert.equal(selected(tree),'lobby-tab-cancellations');
assert.equal(panel(tree),'lobby-cancellations');
assert.equal(h.refs[0].current,false,'Original confirmation clears dirty state');
assert.equal(focused,1,'Approved selection returns focus to visible toggle');
toggle(tree).props.onClick();tree=view();
queue(tree,'cancellations').props.onClick();tree=view();
assert.equal(toggle(tree).props['aria-expanded'],false,'Clean selection of same queue still closes');
assert.equal(focused,2);
toggle(tree).props.onClick();tree=view();
queue(tree,'support').props.onClick();tree=view();
assert.equal(panel(tree),'admin-support');
assert.equal(toggle(tree).props['aria-expanded'],false);
assert.equal(modals.length,2,'Clean transitions do not prompt');
assert.equal(h.calls.length,0,'Opening/choosing queues does not mutate records or handled status');
console.log('MOBILE QUEUE GUARD PASSED: pending/continue-edit preserves open selector, selected queue, panel and dirty state; approved exit closes after original decision and restores toggle focus; clean/same-queue transitions preserved; zero business writes. Handler fixture; browser focus/touch unverified.');
