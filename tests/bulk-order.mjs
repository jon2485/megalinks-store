import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { bulkHeaders, parseBulkSheet, bulkRowError, bulkCartPayload } from '../lib/bulk-order.ts';
const sites = [{ id: 's1', name: 'אתר בדיקה', url: 'https://site.test', active: 1 }];
const customers = [{ id: 'c1', name: 'דנה', email: 'dana@test.test' }, { id: 'c2', name: 'יוסי' }, { id: 'c3', name: 'יוסי' }];
const row = (customer = '', paid = '') => ['אתר בדיקה', 'נושא', 'מותג בדיקה', 'מילת קישור', 'https://target.test/internal/page', '2', customer, paid];
const parse = (r) => parseBulkSheet([bulkHeaders, r], sites, customers)[0];
const paid = parse(row(' דנה ', '400'));
assert.equal(bulkRowError(paid, sites, customers), '');
assert.equal(bulkCartPayload(paid).customer_id, 'c1');
assert.equal(bulkCartPayload(paid).editorial, true);
assert.equal(bulkCartPayload(paid).editorial_words, 400);
assert.equal(bulkCartPayload(paid).quantity, 2);
assert.equal(bulkCartPayload(paid).brand, 'מותג בדיקה');
assert.equal(bulkCartPayload(paid).anchor, 'מילת קישור');
assert(!bulkHeaders.includes('קהל יעד'));
assert(!('audience' in bulkCartPayload(paid)));
const templateView = readFileSync('app/bulk-order-view.tsx', 'utf8');
assert(templateView.includes("exportSpreadsheet('megalinks-bulk-order-template.xlsx', [bulkHeaders])"), 'download contains headers only, never a sample order');
const blankOptional = row(); blankOptional[2] = ''; blankOptional[3] = ''; blankOptional[4] = '';
assert.equal(bulkRowError(parse(blankOptional), sites, customers), '');
assert.equal(bulkCartPayload(paid).target_url, 'https://target.test/internal/page');
assert.equal(bulkCartPayload(parse(row())).editorial, false);
assert(!bulkHeaders.includes('מילים'));
assert(!('words' in bulkCartPayload(parse(row()))));
assert.equal(bulkCartPayload(parse(row('dana@test.test'))).customer_id, 'c1');
assert.equal(bulkCartPayload(parse(row('c1'))).customer_id, 'c1');
assert.match(bulkRowError(parse(row('יוסי')), sites, customers), /כמה לקוחות/);
assert.match(bulkRowError(parse(row('לקוח לא קיים')), sites, customers), /לא נמצא/);
for (const value of ['abc', '0', '-1', '99', '5001', '400.5']) assert.match(bulkRowError(parse(row('', value)), sites, customers), /100/);
for (const value of ['100', '5000']) assert.equal(bulkRowError(parse(row('', value)), sites, customers), '');
assert.match(bulkRowError({ ...paid, quantity: '21' }, sites, customers), /כמות/);
assert.match(bulkRowError({ ...paid, customer_id: 'foreign' }, sites, customers), /אינו זמין/);
assert.match(bulkRowError({ ...paid, target_url: 'javascript:alert(1)' }, sites, customers), /http/);
const legacy = parseBulkSheet([['אתר','נושא','מותג','קהל יעד','עוגן','קישור','מילים','כמות'], ['אתר בדיקה','נושא','','','','','500','2']], sites, customers)[0];
assert.equal(bulkCartPayload(legacy).editorial, false);
assert.equal(bulkCartPayload(legacy).customer_id, '');
assert.throws(() => parseBulkSheet([bulkHeaders, ...Array.from({ length: 501 }, () => row())], sites, customers), /500/);
const workspace = readFileSync('app/workspace.tsx', 'utf8');
assert(!workspace.match(/const clientContentView[^\n]*'bulk'/), 'bulk route must not redirect to personal area');
console.log('Bulk import: customer matching, ambiguous names, paid writing, legacy templates, validation and route checks passed.');
