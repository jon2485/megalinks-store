// Turns home/index.html (the homepage source) into lib/home-page-html.ts, which app/route.ts serves at "/".
// Run after every edit of home/index.html:  node scripts/build-home-page.mjs
import {readFileSync,writeFileSync} from 'node:fs';
const html=readFileSync(new URL('../home/index.html',import.meta.url),'utf8');
for(const marker of ['%%SITE_URL%%','<!--HOME:SCHEMA-->','<!--HOME:POSTS-->','<!--/HOME:POSTS-->'])if(!html.includes(marker))throw new Error('home/index.html is missing '+marker);
writeFileSync(new URL('../lib/home-page-html.ts',import.meta.url),'// Generated by scripts/build-home-page.mjs from home/index.html. Do not edit by hand.\nexport const HOME_HTML='+JSON.stringify(html)+';\n');
console.log('lib/home-page-html.ts written,',html.length,'chars');
