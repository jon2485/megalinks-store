// Copies the legal drafts (design/legal/drafts/<id>.md) into lib/legal-content.generated.ts, which the site reads.
// Run after a draft changes:  node scripts/build-legal-content.mjs
// The section "הערות לעורך הדין (לא לפרסום)" and everything after it stays in the draft file only.
import {readFileSync,writeFileSync,existsSync} from 'node:fs';
import {resolve,dirname} from 'node:path';
import {fileURLToPath} from 'node:url';

const root=resolve(dirname(fileURLToPath(import.meta.url)),'..');
const ids=['terms','privacy','cancellation','supply','accessibility','cookies'];
const out={};
for(const id of ids){
 const file=resolve(root,'design/legal/drafts',id+'.md');
 if(!existsSync(file)){console.warn('missing draft:',id);continue;}
 let text=readFileSync(file,'utf8').replace(/\r\n?/g,'\n');
 const title=(/^#\s+(.+)$/m.exec(text)||[])[1]||'';
 // The first note line after the title is the status line: it carries the version and the date, and the word
 // "טיוטה" while the text is not approved. An approved document replaces it with e.g. "> גרסה 1.0 · בתוקף מיום 1.1.2027".
 const marker=(/^#\s+.+\n+>\s*(.+)$/m.exec(text)||[])[1]||'';
 const updated=(/(\d{1,2}\.\d{1,2}\.\d{4})/.exec(marker)||[])[1]||'';
 const version=(/גרסה\s+([\d.]+\d)/.exec(marker)||[])[1]||'';
 const cut=text.search(/^##\s+הערות לעורך הדין/m);
 if(cut>=0)text=text.slice(0,cut);
 text=text.replace(/^#\s+.+\n+(>\s*.+\n)?/,'').trim()+'\n';
 if(!title)throw new Error('draft without a title: '+id);
 out[id]={title:title.trim(),updated,version,draft:!marker||marker.includes('טיוטה'),markdown:text};
}
const body='// Generated by scripts/build-legal-content.mjs from design/legal/drafts/*.md. Do not edit by hand.\n'+
 'export type LegalContent={title:string;updated:string;version:string;draft:boolean;markdown:string};\n'+
 'export const LEGAL_CONTENT:Record<string,LegalContent>='+JSON.stringify(out,null,1)+';\n';
writeFileSync(resolve(root,'lib/legal-content.generated.ts'),body);
console.log('legal content written for:',Object.keys(out).join(', ')||'(none)');
