import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import ts from 'typescript';
const moduleUrl = code => 'data:text/javascript;base64,'+Buffer.from(code).toString('base64');
const compile = path => ts.transpileModule(readFileSync(path,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText;
const stateUrl = moduleUrl(compile('lib/loading-state.ts'));
const state = await import(stateUrl);
let notifications=0;
const unsubscribe=state.subscribePendingRequests(()=>notifications++);
const finishA=state.beginPendingRequest(),finishB=state.beginPendingRequest();
assert.equal(state.getPendingRequests(),2);
finishA();finishA();assert.equal(state.getPendingRequests(),1);
finishB();assert.equal(state.getPendingRequests(),0);assert.equal(notifications,4);
unsubscribe();
const client = await import(moduleUrl(compile('lib/client.ts').replace("from 'react'",`from '${import.meta.resolve('react')}'`).replace("from './loading-state'",`from '${stateUrl}'`)));
globalThis.window={};
let release;
globalThis.fetch=()=>new Promise(resolve=>{release=resolve;});
const request=client.api('catalog');assert.equal(state.getPendingRequests(),1);
release(Response.json({websites:[]}));assert.deepEqual(await request,{websites:[]});assert.equal(state.getPendingRequests(),0);
globalThis.fetch=async()=>Response.json({error:'denied'},{status:403});
await assert.rejects(client.api('admin/users'),/denied/);assert.equal(state.getPendingRequests(),0);
globalThis.fetch=async()=>{throw new Error('offline');};
await assert.rejects(client.api('me'),/offline/);assert.equal(state.getPendingRequests(),0);
globalThis.fetch=()=>new Promise(resolve=>{release=resolve;});
const quiet=client.api('me','GET',undefined,{background:true});assert.equal(state.getPendingRequests(),0);release(Response.json({}));await quiet;
delete globalThis.window;
const server=client.api('me');assert.equal(state.getPendingRequests(),0);release(Response.json({}));await server;
console.log('Loading request lifecycle checks passed: concurrent requests, duplicate cleanup, success, HTTP/network errors, background polling and SSR.');
